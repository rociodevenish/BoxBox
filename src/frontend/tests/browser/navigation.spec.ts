import { test, expect } from '@playwright/test';
import { mkdirSync,writeFileSync } from 'node:fs';
test('controller submits when UUID secure-context convenience API is unavailable',async({page})=>{
  await page.addInitScript(()=>Object.defineProperty(crypto,'randomUUID',{value:undefined}));
  await page.goto('/race/new');await page.getByRole('button',{name:'Create race'}).click();
  const link=await page.getByRole('link',{name:'Open controller'}).getAttribute('href');await page.goto(link!);
  await page.getByRole('button',{name:'Approve Plan'}).click();await page.getByRole('button',{name:'Confirm plan'}).click();
  await expect(page.getByRole('heading',{name:'Decisions for the next 1 lap'})).toBeVisible();
});
test('retained controller access allows return from public display without granting fresh viewers private access', async ({ page, browser }) => {
  mkdirSync('../../.tools/reports/browser-race/review-05',{recursive:true});
  await page.setViewportSize({width:360,height:800});
  await page.goto('/race/new');
  await page.screenshot({path:'../../.tools/reports/browser-race/review-05/setup-360.png',fullPage:true});
  writeFileSync('../../.tools/reports/browser-race/review-05/select-style.json',JSON.stringify(await page.getByLabel('Preset').evaluate(element=>({backgroundImage:getComputedStyle(element).backgroundImage,backgroundPosition:getComputedStyle(element).backgroundPosition,appearance:getComputedStyle(element).appearance})),null,2));
  await page.getByRole('button', { name: 'Create race' }).click();
  const publicUrl = await page.getByRole('link', { name: 'Open public display' }).getAttribute('href');
  const controllerUrl = await page.getByRole('link', { name: 'Open controller' }).getAttribute('href');
  await page.goto(publicUrl!);
  await page.setViewportSize({width:1920,height:1080});
  await expect(page.getByRole('link', { name: 'Race setup', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Team controller', exact: true })).toHaveAttribute('href', controllerUrl!);
  await page.getByRole('button', { name: 'Interval — to car ahead' }).click();
  await expect(page.getByRole('table', { name: 'Classification — Interval to car ahead' })).toBeVisible();
  const last=await page.getByRole('row').last().boundingBox();expect(last!.y+last!.height).toBeLessThanOrEqual(1080);
  await page.screenshot({path:'../../.tools/reports/browser-race/review-05/display-1920x1080.png'});
  await page.getByRole('link', { name: 'Team controller', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Decisions for the next 5 laps' })).toBeVisible();
  await page.setViewportSize({width:360,height:800});
  await page.getByRole('region',{name:'Car 1 — Driver 1'}).getByRole('button',{name:'Pit',exact:true}).click();
  await page.screenshot({path:'../../.tools/reports/browser-race/review-05/controller-360.png',fullPage:true});
  const fresh = await browser.newContext();
  const viewer = await fresh.newPage();
  await viewer.goto(new URL(publicUrl!, page.url()).href);
  await expect(viewer.getByRole('row')).toHaveCount(23);
  await expect(viewer.getByRole('link', { name: 'Team controller', exact: true })).toHaveCount(0);
  await expect(viewer.getByRole('link', { name: 'Race setup', exact: true })).toBeVisible();
  await fresh.close();
});
