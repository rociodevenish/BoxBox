import { test, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const evidence='../../.tools/reports/browser-race';
test('real display and capability controller resolve exactly one phase', async ({page,context})=>{
 await page.goto('/race/new');
 await page.getByRole('button',{name:'Create race'}).click();
 const controllerUrl=await page.getByRole('link',{name:'Open controller'}).getAttribute('href');
 const displayUrl=await page.getByRole('link',{name:'Open public display'}).getAttribute('href');
 const display=await context.newPage(); await display.goto(displayUrl!);
 await expect(display.getByText('+0.500 s',{exact:true})).toBeVisible();
 const unauthorized=await context.newPage();await unauthorized.goto(controllerUrl!.split('#')[0]);await expect(unauthorized.getByRole('alert')).toContainText('capability');await unauthorized.close();
 await page.goto(controllerUrl!);
 await expect(page.getByRole('heading',{name:'Team 01 controller'})).toBeVisible();
 await page.getByLabel('Car 1 pace').selectOption('Push');
 await page.getByLabel('Car 2 pit instruction').selectOption('Pit');
 await page.getByLabel('Car 2 compound').selectOption('Hard');
 await page.getByRole('button',{name:'Review both cars'}).click();
 await expect(page.getByRole('dialog')).toContainText('Push');
 await expect(page.getByRole('dialog')).toContainText('Hard');
 await page.getByRole('button',{name:'Submit both cars'}).click();
 await expect(display.getByText('phase-result',{exact:true})).toBeVisible();
 await expect(display.getByText('Lap 5 / 6',{exact:true})).toBeVisible();
 await expect(display.getByRole('row')).toHaveCount(23);
 await expect(page.getByLabel('Car 2 compound')).toHaveValue('Hard');
 await expect(page.getByRole('button',{name:'Review both cars'})).toBeDisabled();
 await expect(display.getByText(/estimated/i)).toHaveCount(0);
 mkdirSync(evidence,{recursive:true});
 await display.setViewportSize({width:1920,height:1080});await display.screenshot({path:evidence+'/phase-1920x1080.png'});
 await page.setViewportSize({width:360,height:800});await page.screenshot({path:evidence+'/controller-360.png',fullPage:true});
});
