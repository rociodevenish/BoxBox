import {test,expect} from '@playwright/test';
import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
const captures=resolve(__dirname,'../../../../.tools/reports/gallery');
test('both-car wet compounds remain readable, commit once and survive refresh without forecast leakage',async({page,context})=>{
  await page.setViewportSize({width:360,height:800});await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/race/new');await page.getByLabel('Race distance').selectOption('10');
  await page.getByRole('button',{name:'Create race'}).click();
  const controller=(await page.getByRole('link',{name:'Open controller'}).getAttribute('href'))!;
  const display=(await page.getByRole('link',{name:'Open public display'}).getAttribute('href'))!;
  await page.goto(controller);
  await expect(page.getByText('Tyre rule:',{exact:false})).toContainText('actually race');
  const cars=page.locator('app-two-car-controller .car');
  await cars.nth(0).getByRole('button',{name:'Pit',exact:true}).click();
  await cars.nth(0).getByRole('button',{name:'New compound Intermediate',exact:true}).click();
  await cars.nth(1).getByRole('button',{name:'Pit',exact:true}).click();
  await cars.nth(1).getByRole('button',{name:'New compound Wet',exact:true}).click();
  await expect(cars.nth(0).getByRole('button',{name:'New compound Intermediate',exact:true})).toHaveAttribute('aria-pressed','true');
  mkdirSync(captures,{recursive:true});await page.screenshot({path:resolve(captures,'s10-02-controller-360.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Approve Plan'}).click();await page.getByRole('button',{name:'Confirm plan'}).click();
  await expect(page.getByText('Lap 5 / 10',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('Intermediate',{exact:true}).first()).toBeAttached();
  const publicPage=await context.newPage();await publicPage.setViewportSize({width:1920,height:1080});await publicPage.emulateMedia({reducedMotion:'reduce'});await publicPage.goto(display);
  await expect(publicPage.getByRole('region',{name:'Team forecast'})).toHaveCount(0);
  await expect(publicPage.getByText('Intermediate',{exact:true}).first()).toBeVisible();
  await expect(publicPage.getByText('Wet',{exact:true}).first()).toBeVisible();
  await publicPage.screenshot({path:resolve(captures,'s10-02-display-1920.png'),fullPage:true});
  expect(await publicPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
